open! Hermetic
open Eio_fs_mem_core

type entry = Image.entry =
  | Dir of { path : string; perm : int }
  | File of { path : string; perm : int; contents : string }
  | Symlink of { path : string; target : string }

let find path entries =
  List.find_map
    (function
      | File f when String.equal f.path path -> Some f.contents | _ -> None)
    entries

let load = Image.load

let pp_ml ppf entries =
  Fmt.pf ppf "(* Generated by eio-fs-crunch. Do not edit. *)@.@.";
  Fmt.pf ppf "let entries : Eio_fs_mem.Crunch.entry list =@.";
  Fmt.pf ppf "  Eio_fs_mem.Crunch.@.";
  Fmt.pf ppf "    [@.";
  List.iter
    (function
      | Dir { path; perm } ->
          Fmt.pf ppf "      Dir { path = %S; perm = 0o%03o };@." path perm
      | File { path; perm; contents } ->
          Fmt.pf ppf "      File { path = %S; perm = 0o%03o; contents = %S };@."
            path perm contents
      | Symlink { path; target } ->
          Fmt.pf ppf "      Symlink { path = %S; target = %S };@." path target)
    entries;
  Fmt.pf ppf "    ]@.@.";
  Fmt.pf ppf
    "let load ?os ?clock () = Eio_fs_mem.Crunch.load ?os ?clock entries@."

let interface =
  "(* Generated by eio-fs-crunch. Do not edit. *)\n\n\
   val entries : Eio_fs_mem.Crunch.entry list\n\
   (** The embedded file tree. *)\n\n\
   val load :\n\
  \  ?os:[< `Linux | `Macos | `Windows ] ->\n\
  \  ?clock:_ Eio.Time.clock ->\n\
  \  unit ->\n\
  \  [ `Close | Eio.Fs.dir_ty ] Eio.Path.t\n\
   (** [load ~os ~clock ()] is the root of a new in-memory filesystem holding\n\
  \    {!entries}, as {!Eio_fs_mem.Crunch.load} makes it. *)\n"
